"""Генерирует тестовые векторы Veil v1 в veil-protocol/test-vectors/veil-v1.json.

Запуск: python -m tools.gen_vectors. Векторы детерминированы, кроме шифртекстов sealed box
(они случайны по построению; проверяется только расшифровка).
"""
from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

from nacl.public import PrivateKey, SealedBox
from nacl.signing import SigningKey

from veil import market
from veil.core import api as coreapi
from veil.core import privacy
from veil.core.crypto import bip39, keys, poprf
from veil.core.identity import nick
from veil.core.protocol import b64, content, envelope, errors, hidden, jcs, keysdoc
from veil.core.wallet import issue

OUT = Path(__file__).resolve().parents[2] / "veil-protocol/test-vectors/veil-v1.json"


def h(b: bytes) -> str:
    return b.hex()


def det(label: str) -> bytes:
    return hashlib.sha256(b"veil/v1/test-vector/" + label.encode()).digest()


def main() -> None:
    v: dict = {"version": 1, "note": "Generated by veil-client/tools/gen_vectors.py. Do not edit by hand."}

    jcs_cases = [
        '{"b":2,"a":1,"c":{"z":[3,2,1],"y":null}}',
        '{"\\ue000":1,"\\ud83d\\ude00":2,"a":3,"\\u00e9":4}',
        '{"s":"tab\\tline\\nquote\\"back\\\\slash\\u0001\\u001f\\u007f\\u2028/é😀"}',
        '{"t":true,"f":false,"n":-9007199254740991,"m":9007199254740991,"z":0}',
        '[]', '{}', '"Вася"',
    ]
    v["jcs"] = [{"input": c, "canonical": jcs.canonicalize(jcs.strict_loads(c)).decode()} for c in jcs_cases]
    v["json_reject"] = ['{"a":1,"a":2}', '{"a":1.5}', '{"a":1e3}', '{"a":NaN}', '{"a":9007199254740992}',
                        '{"a":-0.0}', '{"a":"\\ud800"}']

    v["base64url"] = {
        "valid": [{"b64": b64.enc(x), "hex": h(x)} for x in (b"", b"\x00", b"\xff\xfe", b"abc", bytes(range(32)))],
        "reject": ["AA==", "AB", "A", "AA AA", "AA+/", "_w=", "AAF", "AB=="],
    }

    # Личность (spec/02): 12 слов → seed → корень; устройство и ключ шифрования — случайные (здесь детерминированы).
    # Официальные векторы BIP-39 (Trezor), HKDF (RFC 5869) и JCS (RFC 8785) — в reference.json.
    entropy = det("mnemonic")[:16]
    m = bip39.from_entropy(entropy)
    seed = bip39.to_seed(m)
    root = keys.root_from_seed(seed)
    id_pk = bytes(root.verify_key)
    v["identity"] = [{"entropy": h(entropy), "mnemonic": m, "seed": h(seed), "id_pk": b64.enc(id_pk),
                      "tag": keys.tag(id_pk)}]
    dev = SigningKey(det("device_sk"))
    seq, exp = 1792000000, 1792000000 + keys.ENC_LIFETIME
    enc = PrivateKey(det("enc_sk"))
    dmsg = keys.device_message(id_pk, bytes(dev.verify_key), seq)
    emsg = keys.enc_message(id_pk, bytes(enc.public_key), exp)
    match = {"id_pk": b64.enc(id_pk), "nick": "Вася", "dev_pk": b64.enc(bytes(dev.verify_key)), "seq": seq,
             "dev_sig": b64.enc(root.sign(dmsg).signature), "enc_pk": b64.enc(bytes(enc.public_key)), "enc_exp": exp,
             "enc_sig": b64.enc(dev.sign(emsg).signature)}
    assert keys.verify_lookup_match(match, keys.tag(id_pk), now=seq).enc_pk == bytes(enc.public_key)
    other = SigningKey(det("other_root"))

    def forged(why, **kw):
        mm = dict(match, **kw)
        try:
            keys.verify_lookup_match(mm, keys.tag(id_pk), now=seq)
        except keys.KeyMismatchError:
            return {"why": why, "match": mm}
        raise AssertionError(why)
    v["device"] = {
        "note": "dev_sig = Ed25519(root, device_message), enc_sig = Ed25519(dev, enc_message); now = seq",
        "device_sk": h(det("device_sk")), "enc_sk": h(bytes(enc)),
        "device_message": h(dmsg), "enc_message": h(emsg), "now": seq, "tag": keys.tag(id_pk), "match": match,
        "reject": [
            forged("enc_pk substituted (server swapped the key)",
                   enc_pk=b64.enc(bytes(PrivateKey(det("evil")).public_key))),
            forged("device certified by another root", dev_sig=b64.enc(other.sign(dmsg).signature)),
            forged("seq changed after signing", seq=seq + 1),
            forged("enc_exp extended after signing", enc_exp=exp + 86400),
            forged("expired enc key", enc_exp=seq - 1,
                   enc_sig=b64.enc(dev.sign(keys.enc_message(id_pk, bytes(enc.public_key), seq - 1)).signature)),
        ],
    }
    v["bip39_reject"] = [
        "abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon",
        "abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon",
        "abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon zzzz",
    ]
    v["tag"] = [{"id_pk": b64.enc(pk), "tag": keys.tag(pk)} for pk in (bytes(32), bytes([255] * 32), id_pk)]

    ps = det("post_secret")
    v["post_key"] = [{"post_secret": h(ps), "post_pk": b64.enc(bytes(keys.post_signing_key(ps).verify_key))}]

    # Константы протокола: единый источник истины для обеих реализаций (тесты сверяют их со своими, spec/00).
    v["limits"] = {"version": envelope.VERSION, "envelope_json_max": envelope.MAX_PLAINTEXT,
                   "clock_skew_seconds": envelope.CLOCK_SKEW, "response_part_chars": envelope.RESP_PART_CHARS,
                   "response_parts_max": envelope.MAX_RESP_PARTS, "tokens_per_day": issue.MAX_PER_DAY,
                   "issue_days_max": issue.MAX_DAYS, "nick_graphemes": [nick.MIN_GRAPHEMES, nick.MAX_GRAPHEMES],
                   "nick_codepoints_max": nick.MAX_CODEPOINTS, "nick_marks_max": nick.MAX_MARKS,
                   "tag_chars": keys.TAG_CHARS, "edit_limit": 5, "edit_window_hours": 24,
                   "hidden_text_units_max": hidden.MAX_TEXT_UNITS, "hidden_payload_max": hidden.MAX_PAYLOAD,
                   "envelope_doc_json_max": envelope.MAX_DOC_PLAINTEXT,
                   "response_json_max": envelope.MAX_RESPONSE}
    assert coreapi.TOKENS_PER_DAY == issue.MAX_PER_DAY
    # Коды ошибок ответа и форматы идентификаторов — тоже один список на обе стороны.
    v["error_codes"] = list(errors.CODES)
    # Смысл кодов: какие ответы сервер не сохраняет (повтор выполняется заново) и после каких токен потрачен.
    v["error_semantics"] = {"not_saved": [errors.E_INTERNAL, errors.E_RATE, errors.E_TELEGRAM, errors.E_PENDING],
                            "token_spent": list(errors.TOKEN_SPENT)}
    v["formats"] = {"kid": envelope.KID_PATTERN, "op": envelope.OP_PATTERN, "id": envelope.ULID_PATTERN}
    v["text_sha256"] = [{"text": t, "sha256": content.text_sha256(t)} for t in ("", "Привет, мир", "a\nb 😀")]
    ent_cases = [[], [{"offset": 0, "length": 7, "type": "bold"}, {"offset": 7, "length": 6, "type": "italic"}],
                 [{"offset": 3, "length": 4, "type": "text_link", "url": "https://example.com/x"},
                  {"offset": 8, "length": 3, "type": "pre", "language": "go"},
                  {"offset": 12, "length": 2, "type": "custom_emoji", "custom_emoji_id": "5368324170671202286"},
                  {"offset": 15, "length": 4, "type": "text_mention",
                   "user": {"id": 123456789, "is_bot": False, "first_name": "X"}}],
                 [{"offset": 0, "length": 5, "type": "date_time", "unix_time": 1792000000, "date_time_format": "r"}]]
    v["entities_sha256"] = [{"entities": c, "sha256": content.entities_sha256(c)} for c in ent_cases]

    inbox_sk = PrivateKey(det("inbox_sk"))
    resp_sk = PrivateKey(det("resp_sk"))
    ts = 1792000000
    token = {"scheme": "poprf-r255-v1", "kid": "t1", "day": "2026-10-14",
             "input": b64.enc(det("token_input")), "output": b64.enc(det("token_output") * 2)}
    env, _ = envelope.build(
        "post.create", "identity", dev, "i1", ts=ts, id_="01K7ZZ0000000000000000TEST", resp_sk=resp_sk,
        token=token, content={"kind": "text", "text_sha256": content.text_sha256("Привет, мир"),
                                     "entities_sha256": content.entities_sha256([]), "files": []},
        body={"post_pk": v["post_key"][0]["post_pk"], "reply_to": 13, "hidden": None,
              "options": {"link_preview": False}})
    sealed = envelope.seal(env, bytes(inbox_sk.public_key))
    assert envelope.open_envelope(sealed, inbox_sk, now=ts) == env
    v["envelope"] = {
        "inbox_sk": h(bytes(inbox_sk)), "inbox_pk": b64.enc(bytes(inbox_sk.public_key)),
        "now": ts, "object": env,
        "signing_input": envelope.signing_input(env).decode(),
        "sealed": sealed,
    }

    def tampered(mut):
        e = json.loads(json.dumps(env))
        mut(e)
        return envelope.PREFIX + b64.enc(SealedBox(inbox_sk.public_key).encrypt(b"\x00" + jcs.canonicalize(e)))

    def resign(e):
        e["sig"] = b64.enc(dev.sign(envelope.signing_input(e)).signature)

    rejects = []
    rejects.append({"why": "body changed after signing", "code": "E_SIG",
                    "sealed": tampered(lambda e: e["body"].__setitem__("reply_to", 14))})
    rejects.append({"why": "unknown top-level field (signed)", "code": "E_MALFORMED",
                    "sealed": tampered(lambda e: (e.__setitem__("x", 1), resign(e)))})
    rejects.append({"why": "clock skew 301s", "code": "E_CLOCK",
                    "sealed": tampered(lambda e: (e.__setitem__("ts", ts - 301), resign(e)))})
    rejects.append({"why": "unsupported version", "code": "E_VERSION",
                    "sealed": tampered(lambda e: (e.__setitem__("v", 99), resign(e)))})
    # Формат полей проверяется до подписи; типы v и ts — логическое значение не целое число (spec/04).
    rejects.append({"why": "v is true (signed)", "code": "E_VERSION",
                    "sealed": tampered(lambda e: (e.__setitem__("v", True), resign(e)))})
    rejects.append({"why": "ts is true (signed)", "code": "E_MALFORMED",
                    "sealed": tampered(lambda e: (e.__setitem__("ts", True), resign(e)))})
    rejects.append({"why": "ts is a string (signed)", "code": "E_MALFORMED",
                    "sealed": tampered(lambda e: (e.__setitem__("ts", str(ts)), resign(e)))})
    rejects.append({"why": "op with a capital letter (signed)", "code": "E_MALFORMED",
                    "sealed": tampered(lambda e: (e.__setitem__("op", "Post.create"), resign(e)))})
    rejects.append({"why": "op broken without re-signing: format is checked before the signature",
                    "code": "E_MALFORMED",
                    "sealed": tampered(lambda e: e.__setitem__("op", "post.CREATE"))})
    rejects.append({"why": "id in lower case (signed)", "code": "E_MALFORMED",
                    "sealed": tampered(lambda e: (e.__setitem__("id", e["id"].lower()), resign(e)))})
    rejects.append({"why": "kid with a slash (signed)", "code": "E_MALFORMED",
                    "sealed": tampered(lambda e: (e.__setitem__("kid", "i/1"), resign(e)))})
    rejects.append({"why": "resp_pk of 31 bytes (signed)", "code": "E_MALFORMED",
                    "sealed": tampered(lambda e: (e.__setitem__("resp_pk", b64.enc(bytes(31))), resign(e)))})

    def neutral_key(e):
        # Нейтральная точка Ed25519 (y = 1) и «подпись» R = нейтральная точка, S = 0: верна для любого сообщения
        # в реализациях без проверки малого порядка (spec/04).
        neutral = b"\x01" + bytes(31)
        e["auth"]["pk"] = b64.enc(neutral)
        e["sig"] = b64.enc(neutral + bytes(32))
    rejects.append({"why": "auth.pk is the neutral point, sig = neutral point || 0", "code": "E_MALFORMED",
                    "sealed": tampered(neutral_key)})
    rejects.append({"why": "clock skew +301s", "code": "E_CLOCK",
                    "sealed": tampered(lambda e: (e.__setitem__("ts", ts + 301), resign(e)))})

    def pad_to(e, size):
        # Подгоняет канонический JSON ровно до size байт полем body (подпись фиксированной длины).
        e["body"] = {"pad": ""}
        resign(e)
        e["body"] = {"pad": "a" * (size - len(jcs.canonicalize(e)))}
        resign(e)
        assert len(jcs.canonicalize(e)) == size
    rejects.append({"why": "text envelope with 3001 bytes of JSON (limit 3000)", "code": "E_DECRYPT",
                    "sealed": tampered(lambda e: pad_to(e, envelope.MAX_PLAINTEXT + 1))})
    rejects.append({"why": "not an envelope", "code": "E_NOT_ENVELOPE", "sealed": "hello"})
    rejects.append({"why": "garbage ciphertext", "code": "E_DECRYPT", "sealed": "VEIL1 " + b64.enc(bytes(80))})
    for r in rejects:
        try:
            envelope.open_envelope(r["sealed"], inbox_sk, now=ts)
        except envelope.ProtocolError as e:
            assert e.code == r["code"], (r["why"], e.code)
        else:
            raise AssertionError(r["why"])
    v["envelope_reject"] = rejects

    server_sig = SigningKey(det("server_sig"))
    resp = envelope.build_response(env["id"], server_sig, result={"n": 246, "url": "https://t.me/c/1/2"})
    v["response"] = {
        "server_sig_pk": b64.enc(bytes(server_sig.verify_key)), "resp_sk": h(bytes(resp_sk)),
        "object": resp, "signing_input": envelope.signing_input(resp, envelope.CTX_RESPONSE).decode(),
        "sealed": envelope.seal_response(resp, bytes(resp_sk.public_key)),
    }

    def signed_response(**fields):
        """Ответ с произвольным составом, подписанный server_sig, запечатанный на resp_sk (в обход seal_response)."""
        r = dict(fields)
        r["sig"] = b64.enc(server_sig.sign(envelope.signing_input(r, envelope.CTX_RESPONSE)).signature)
        return envelope.RESP_PREFIX + b64.enc(SealedBox(resp_sk.public_key).encrypt(b"\x00" + jcs.canonicalize(r)))

    def padded_response(size):
        # Ответ, канонический JSON которого ровно size байт (подпись фиксированной длины).
        def make(k):
            r = {"v": 1, "re": env["id"], "ok": True, "result": {"pad": "a" * k}}
            r["sig"] = b64.enc(server_sig.sign(envelope.signing_input(r, envelope.CTX_RESPONSE)).signature)
            return r
        r = make(size - len(jcs.canonicalize(make(0))))
        assert len(jcs.canonicalize(r)) == size
        return r

    good_re, bad_code = env["id"], {"code": "E_RATE", "retry_after": 3}
    too_big = padded_response(envelope.MAX_RESPONSE + 1)
    response_reject = [
        ("ok=true without result", "E_MALFORMED", signed_response(v=1, re=good_re, ok=True)),
        ("ok=false without error", "E_MALFORMED", signed_response(v=1, re=good_re, ok=False)),
        ("ok=true with error", "E_MALFORMED",
         signed_response(v=1, re=good_re, ok=True, result={}, error=bad_code)),
        ("error is a string", "E_MALFORMED", signed_response(v=1, re=good_re, ok=False, error="E_RATE")),
        ("error without code", "E_MALFORMED", signed_response(v=1, re=good_re, ok=False, error={"overflow": 1})),
        ("retry_after is a string", "E_MALFORMED",
         signed_response(v=1, re=good_re, ok=False, error={"code": "E_RATE", "retry_after": "3"})),
        ("extra top-level field", "E_MALFORMED", signed_response(v=1, re=good_re, ok=True, result={}, x=1)),
        ("ok is a string", "E_MALFORMED", signed_response(v=1, re=good_re, ok="true", result={})),
        ("foreign re", "E_MALFORMED", signed_response(v=1, re="01K7ZZ0000000000000000OTHR", ok=True, result={})),
        ("v is 2", "E_VERSION", signed_response(v=2, re=good_re, ok=True, result={})),
        ("JSON of MAX_RESPONSE+1 bytes, sealed directly", "E_DECRYPT",
         envelope.RESP_PREFIX + b64.enc(SealedBox(resp_sk.public_key).encrypt(
             b"\x00" + jcs.canonicalize(too_big)))),
    ]
    for why, code, sealed_r in response_reject:
        try:
            envelope.open_response(sealed_r, resp_sk, bytes(server_sig.verify_key), good_re)
        except envelope.ProtocolError as e:
            assert e.code == code, (why, e.code)
        else:
            raise AssertionError(why)
    v["response_reject"] = {
        "note": "Same resp_sk and server_sig as `response`. Open each with expect_id; the code is the expected error.",
        "server_sig_pk": b64.enc(bytes(server_sig.verify_key)), "resp_sk": h(bytes(resp_sk)), "expect_id": good_re,
        "cases": [{"why": w, "code": c, "sealed": t} for w, c, t in response_reject],
    }

    big = envelope.build_response(env["id"], server_sig, result={"feed": ["я" * 100] * 60})
    big_sealed = envelope.seal_response(big, bytes(resp_sk.public_key))
    v["response_parts"] = {"note": "Same resp_sk and server_sig as `response`; parts may arrive in any order.",
                           "object": big, "parts": envelope.split_response(big_sealed)}
    assert len(v["response_parts"]["parts"]) > 1

    cases = [
        ("Вася", True), ("  Вася  ", True), ("Ва", True), ("В", False), ("x" * 32, True), ("x" * 33, False),
        ("👨\u200d👩\u200d👧\u200d👦👨\u200d👩\u200d👧\u200d👦", True), ("Вася·7f3a", False), ("Ва\u200bся", False),
        ("Ва\u202eся", False),
        ("Ва\nся", False), ("Ва  ся", False), ("Ва\u00a0ся", False), ("éé", True), ("Ва ся", True),
        ("Ва\u200dся", False), ("👍🏽\u200d", False), ("👍🏽\u200d👍x", True),
        # невидимые заполнители и селекторы вариантов (2026-10-16)
        ("\u3164\u3164", False), ("Ва\u034fся", False), ("Ва\ufe00ся", False), ("a\u00adb", False), ("❤️Love", True),
        # пределы: знаки на графему и кодовые точки
        ("q\u0301\u0302\u0303a", True), ("q\u0301\u0302\u0303\u0304a", False),
        # селекторы вида — только как часть эмодзи; пустой символ Брайля и «№» запрещены (2026-10-19)
        ("Ва\ufe0fся", False), ("Ва\ufe0eся", False), ("\ufe0fВася", False), ("❤\ufe0f\ufe0fx", False),
        ("☺\ufe0eок", True), ("1\ufe0f\u20e3x", True), ("🏳\ufe0f\u200d🌈x", True),
        ("\u2800\u2800", False), ("Ва\u2800ся", False), ("№1", False), ("Вася №5", False),
        ("👨\u200d👩\u200d👧\u200d👦" * 18, True), ("👨\u200d👩\u200d👧\u200d👦" * 19, False),
    ]
    # Ключи похожести ника (spec/02, UTS #39): какие ники совпадают при той же метке. Считает сервер; кейсы — его тест.
    v["nick_key"] = {
        "same": [["Anna", "Аnna", "АNNA", "anna", "A n n a"], ["Вася", "Bacя", "ВАСЯ", "вася", "ʙacᴙ"],
                 ["Bob0", "BobO", "Воb0"], ["l1l", "I|l", "1Il"], ["paypal", "раураl"],
                 # знаки препинания и символы не различают ники одной метки (сценарий «двойник», 2026-10-17)
                 ["Ромашка у дороги", "Ромашка у дороги!", "Ромашка-у-дороги", "«Ромашка» у дороги…",
                  "Ромашка у дороги ❤️"]],
        "different": [["Вася", "Петя"], ["Имя", "Им"], ["Вася", "Васяя"], ["ёлка", "елка"],
                      ["Ромашка у дороги", "Ромашка у порога"]],
    }
    v["nick"] = []
    for inp, ok in cases:
        try:
            out = nick.normalize(inp)
            assert ok, inp
            v["nick"].append({"input": inp, "ok": True, "normalized": out})
        except nick.NickError:
            assert not ok, inp
            v["nick"].append({"input": inp, "ok": False})

    day = "2026-10-14"
    states = [poprf.blind(det(f"cross_input/{i}"), int.from_bytes(det(f"cross_blind/{i}") * 2, "little") % poprf.r255.L)
              for i in range(5)]
    v["poprf_cross_request"] = {
        "day": day, "info": "veil/v1/day/" + day, "key_seed": h(det("issuer_seed")),
        "inputs": [h(s_.input) for s_ in states], "blinds": [h(poprf.r255.scalar_to_bytes(s_.blind)) for s_ in states],
        "blinded": [h(s_.blinded) for s_ in states],
    }

    # Скрытый контент (spec/07).
    hp = hidden.payload("Секрет 😀 https://example.com", [{"type": "url", "offset": 10, "length": 19}])
    hk, hn = det("hidden_key"), det("hidden_nonce")[:24]
    hblob, _ = hidden.seal_all(hp, hk, hn)
    v["hidden_all"] = {"payload": hp.decode(), "key": b64.enc(hk), "blob": b64.enc(hblob),
                       "callback_n": 246, "callback_data": hidden.callback_data(246, hk)}
    rk = PrivateKey(det("hidden_recipient"))
    # «Лично для» несёт post_pk своего поста (получатель сверяет его с записью ленты) и выравнивается до 256 байт.
    hpp = hidden.padded(hidden.payload("Секрет 😀 https://example.com", [{"type": "url", "offset": 10, "length": 19}],
                                       post_pk=v["post_key"][0]["post_pk"]))
    v["hidden_to"] = {"note": "sealed box is random; recipient must open it", "enc_sk": h(bytes(rk)),
                      "payload": hpp.decode(), "blob": b64.enc(hidden.seal_to(hpp, bytes(rk.public_key)))}
    v["padding"] = {"pad_block": hidden.PAD_BLOCK, "padded_payload_len": len(hpp),
                    "padme": [[n, hidden.padme(n)]
                              for n in (0, 1, 2, 9, 100, 1000, 4097, 65537, 1 << 20, 19 * 10 ** 6)]}
    v["hidden_reject"] = [h(hidden.seal_all(b'{"text":""}', hk, hn)[0]),
                          h(hidden.seal_all(b'{"text":"x","extra":1}', hk, hn)[0]),
                          h(hidden.seal_all(b'{"text":"x","text":"y"}', hk, hn)[0])]

    # Выдача токенов (spec/03): полный запрос VEILREQ на два дня разных недель (два kid).
